# 01-04 §2 — 큐가 어디에 생기는가. "출력 링크"·"출력 포트"가 본문에 0건이라
# 학습자가 "같은 출력 링크로 나간다는 게 뭔 말이지"라고 물은 자리다.
# 본문 근거: d(queue) 는 "링크가 빌 때까지 버퍼에서 기다림"이고 "앞서 도착해 기다리는 패킷 수"가 정한다.
#   손실은 "큐 용량이 유한하므로 ... 패킷이 도착했을 때 큐가 꽉 차 있을 수 있습니다. 그때 라우터는 그 패킷을 버립니다."
#   트래픽 강도 La/R 의 R 이 곧 이 출력 링크의 전송률이다.
# 논점 둘 — 큐는 라우터가 아니라 '출력 링크마다' 생긴다는 것, 그리고 그 줄의 끝이 손실이라는 것.
# 타입 스펙: type-data-flow — 여러 갈래가 한 지점으로 모이고 그 지점의 처리 능력이 병목이 된다.
#   축약: 라우터 내부의 스위칭 패브릭은 그리지 않는다(04-01 의 축이다). 여기서는 모이는 것까지만 본다.
