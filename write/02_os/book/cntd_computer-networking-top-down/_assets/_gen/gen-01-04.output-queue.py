IN = [(150, "링크 A 에서", "→ C 로 가야 함"), (250, "링크 B 에서", "→ C 로 가야 함"), (350, "링크 D 에서", "→ E 로 가야 함")]
for y, name, dest in IN:
    c = ACC if "C" in dest else SOFT
    d.tone(24, y, 190, 62, c, 6, "10", 1.2)
    d.t(44, y + 26, name, 12, c, KR, "start", 600)
    d.t(44, y + 46, dest, 11, MUTED, KR, "start")
    d.arrow([(214, y + 31), (268, y + 31)], c, "acc" if c is ACC else "soft", 1.3)

