# 03-01 §1 — 트랜스포트가 IP 의 배달을 "호스트 사이"에서 "프로세스 사이"로 좁힌다.
# 본문 근거: "이 층의 자리를 한 단어가 잡습니다. 논리적 통신입니다. 애플리케이션의 관점에서는
#   두 호스트가 직접 연결된 것처럼 보이는데, 실제로는 지구 반대편에 있고 수많은 라우터와 온갖 링크를 거칩니다."
#   그리고 §2 의 "IP 는 호스트 사이의 논리적 통신을 줍니다".
# 논점은 겹이 하나 늘 때 주소도 하나 는다는 것 — IP 주소로 호스트를, 포트로 프로세스를.
# 타입 스펙: type-nested — 안쪽 겹이 바깥 겹을 전제로 서고, 범위가 좁아지는 것이 그림의 뜻이다.
#            축약: 라우터 대수와 링크 종류는 아래 띠에 글로만 적는다. 경로 자체가 논점이 아니다.
import sys; sys.path.insert(0, ".")
from dd import D, ACC, MUTED, SOFT, INK, OK, INFO, PAPER2, RULE, KR, MONO

W, H = 1000, 640
d = D(W, H, "COMPUTER NETWORKING TOP-DOWN · 03-01 §1",
      "겹이 하나 늘면 주소도 하나 늡니다",
      "IP 가 호스트까지 데려다주고, 트랜스포트가 그 안에서 프로세스까지 좁힌다. "
      "바깥 겹은 IP 주소로 호스트를 찾고 안쪽 겹은 포트로 프로세스를 찾는다.",
      "'논리적'이란 곧바로 이어진 것처럼 보인다는 뜻입니다")

d.tone(40, 140, 920, 300, INFO, 8, "0E", 1.4)
d.t(64, 172, "IP 가 주는 것 · 호스트 사이 논리적 통신", 13, INFO, KR, "start", 600)
d.t(64, 194, "주소는 IP 주소 하나입니다. 여기까지는 어느 프로세스에게 줄지 모릅니다.", 11, MUTED, KR, "start")

d.tone(90, 214, 820, 152, OK, 8, "0E", 1.4)
d.t(114, 244, "트랜스포트가 더하는 것 · 프로세스 사이 논리적 통신", 13, OK, KR, "start", 600)
d.t(114, 266, "주소가 하나 더 붙습니다. 포트가 그것입니다.", 11, MUTED, KR, "start")

d.chip(210, 322, "프로세스 · 포트 49152", OK)
d.chip(790, 322, "프로세스 · 포트 80", OK)
d.arrow([(330, 316), (688, 316)], OK, "ok", 1.4)
d.arrow([(670, 330), (312, 330)], OK, "ok", 1.4)

d.chip(210, 404, "호스트 A · 203.0.113.5", INFO)
d.chip(790, 404, "호스트 B · 198.51.100.9", INFO)
d.arrow([(350, 398), (668, 398)], INFO, "info", 1.4)
d.arrow([(650, 412), (332, 412)], INFO, "info", 1.4)

d.box(24, 470, W - 48, 86, PAPER2, RULE, 0.9, 6)
d.t(44, 496, "그런데 그 선은 실제로 존재하지 않습니다", 12, INK, KR, "start", 600)
d.t(44, 518, "두 호스트는 지구 반대편에 있고 사이에 라우터가 여럿, 링크가 여러 종류 놓여 있습니다. 곧바로 이어진 것처럼 보일 뿐입니다.",
    11, MUTED, KR, "start")
d.t(44, 540, "그래서 '논리적'입니다. 트랜스포트 프로토콜은 종단 시스템에서만 돌고 중간의 라우터는 이 겹을 아예 보지 않습니다.",
    11, ACC, KR, "start")

d.legend(H - 44, [("IP 가 책임지는 범위", INFO), ("트랜스포트가 좁힌 범위", OK), ("착시가 생기는 자리", ACC)])
d.save("03-01.logical-communication.svg")
print("ok logical-communication")
