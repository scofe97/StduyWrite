# 03-04 §4 시나리오 1 — 원문 Figure 3.43·3.44. 호스트 둘이 무한 버퍼 라우터 하나를 거쳐 용량 R 의 링크를 나눠 쓴다.
# 본문 근거: "0 에서 R/2 사이면 처리량이 보내는 속도와 같다 · R/2 를 넘으면 처리량은 R/2 에 묶인다 ·
#   R/2 에 가까워질수록 평균 지연이 점점 커지고 넘으면 무한대". 곡선 모양은 원문 그림의 개략이다.
# 타입 스펙: type-line — 부하에 따른 처리량·지연 곡선. 위쪽 띠의 토폴로지는 곡선이 어느 망의 것인지 알리는 문맥이다.
import sys; sys.path.insert(0, ".")
from _cc_common import *

W, H = 1000, 560
d = D(W, H, "COMPUTER NETWORKING TOP-DOWN · 03-04 §4",
      "시나리오 1 — 버퍼가 무한하면 잃지는 않지만 기다립니다",
      "원문 Figure 3.43·3.44. 처리량은 R/2 에서 멈추고, 그 근처에서 큐잉 지연이 무한대로 치솟는다.",
      "왼쪽이 처리량, 오른쪽이 평균 지연입니다. 가로축은 한 호스트가 보내는 속도 λin 입니다")

# 토폴로지 띠
ty = 150
host(d, 90, ty - 22, "A"); host(d, 90, ty + 22, "B")
router(d, 300, ty, "R", "버퍼 무한")
fan_in(d, [112, 112], [ty - 22, ty + 22], 240, ty, 282)
link(d, 318, ty, 440, ty, ACC, "용량 R 의 링크", -10)
host(d, 520, ty - 22, "C"); host(d, 520, ty + 22, "D")
fan_out(d, 440, ty, 480, [ty - 22, ty + 22], 496)
d.t(560, ty - 6, "오류 회복도, 흐름·혼잡 제어도 없음", 11, MUTED, KR, "start")
d.t(560, ty + 12, "A 와 B 가 같은 속도 λin 으로 보내고, 둘 다 R 을 나눠 씀", 11, MUTED, KR, "start")

# 곡선 둘
xt = [(0, "0"), (1 / 3, "R/4"), (2 / 3, "R/2"), (1, "3R/4")]
c1 = Chart(d, 24, 196, 470, 300, "λin (한 호스트의 송신 속도)", "처리량 λout", xt, [(0, "0"), (0.5, "R/4"), (1, "R/2")])
c1.series([(0, 0), (1 / 6, 0.25), (1 / 3, 0.5), (0.5, 0.75), (2 / 3, 1), (5 / 6, 1), (1, 1)], ACC, focal=True)
c1.note(0.70, 0.88, "R/2 를 넘어도 R/2 에 묶", ACC, "start")
c2 = Chart(d, 506, 196, 470, 300, "λin (한 호스트의 송신 속도)", "평균 지연", xt, [(0, "0"), (0.5, ""), (1, "∞")])
pts = [(0, 0.02), (0.13, 0.05), (0.27, 0.1), (0.4, 0.18), (0.5, 0.3), (0.57, 0.46), (0.61, 0.66), (0.65, 0.92)]
c2.series(pts, WARN, focal=True)
d.line(c2.px(2 / 3), c2.T, c2.px(2 / 3), c2.B, WARN, 0.8, "3 4")
c2.note(0.3, 0.8, "R/2 에 가까워질수록 큐가 길어지고", WARN, "start")
c2.note(0.7, 0.55, "R/2 부터는 무한대", WARN, "start")

d.legend(H - 44, [("처리량 — 링크를 다 쓰는 것처럼 보임", ACC), ("지연 — 첫 번째 대가", WARN)])
d.save("03-04.cc-scenario1.svg")
