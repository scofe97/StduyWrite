# 03-03 §5 — 송신자가 반응하는 사건이 셋뿐이고, 그 셋으로 모든 시나리오가 처리된다.
# 본문 근거(세 사건 그대로): "위층에서 데이터가 옴 — 세그먼트로 싸서 IP 에 넘깁니다. 다른 세그먼트 때문에
#   타이머가 이미 돌고 있지 않으면 타이머를 시작합니다." · "타임아웃 — 타임아웃을 일으킨 세그먼트를
#   재전송하고 타이머를 다시 시작합니다." · "ACK 도착 — y > SendBase 면 ... SendBase 를 갱신하고,
#   미확인 세그먼트가 남아 있으면 타이머를 다시 시작합니다."
#   그리고 "타이머는 가장 오래된 미확인 세그먼트의 것이라 생각하면 됩니다."
# 논점: 상태는 사실상 둘이고 사건은 셋이다. 그 작은 표가 앞 편의 세 시나리오를 다 덮는다.
# 타입 스펙: type-state — 사건이 상태를 옮기거나 제자리에 두는 관계. 자기 자신으로 돌아오는 전이가
#   "타이머만 다시 시작"에 해당해 상태 수가 늘지 않는다는 것을 보인다.
#   축약: 흐름 제어·혼잡 제어가 거는 창 제약은 그리지 않는다. 03-04·03-05 의 몫이다.
