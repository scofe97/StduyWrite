# 노트의 읽기: 각 칸 옆 절 번호가 본문에서 그 부분을 다루는 곳이다. 개념이 흐름의 어느
#       지점에서 작동하는지를 보이는 것이 목적이라, 값·식은 본문에 맡기고 여기서는 자리만 짚는다.
#   RFC 9293 §3.1(연결 수립·해제), RFC 5681 §3.1(min{cwnd, rwnd}).
# 타입 스펙: type-sequence — 참여자 레인 + 시간축 왕복. 시간은 위에서 아래로만 흐른다.
#
# 상태 칩(state)은 ASCII 만 담는다. dd.py 의 폭 계산이 문자당 7px 이라 한글을 넣으면 칩이 글자보다 좁아진다.
import sys; sys.path.insert(0, ".")
from dd import Seq, ACC, MUTED, SOFT, INK, OK, WARN, INFO, RULE, KR, MONO

W, H = 1000, 760

d = Seq(W, H, "COMPUTER NETWORKING TOP-DOWN · 03-04",
        "한 연결의 처음부터 끝까지, 무엇이 송신을 조이는가",
        "세우고 · 조이고 · 허무는 세 국면. 조이는 장치가 둘이고 실제 한도는 둘 중 작은 쪽이다.",
        "받는 쪽은 숫자로 알려 주고, 망은 아무도 안 알려 줘서 추측합니다")

d.lanes([("보내는 쪽", "송신 버퍼 · cwnd 추정"),
         ("받는 쪽", "수신 버퍼 · rwnd 통보")])
d.rails(660)

# ── 세우기 §2·§3
d.msg("보내는 쪽", "받는 쪽", "SYN", 172, ACC, sub="§2 첫 단계 — 아직 자원은 안 잡힘")
d.msg("받는 쪽", "보내는 쪽", "SYN + ACK", 214, ACC,
      sub="§2 여기서 서버 자원이 잡힘 — §3 SYN 플러드가 노리는 자리")
d.msg("보내는 쪽", "받는 쪽", "ACK", 256, ACC, sub="§2 셋째 단계 — 이때부터 데이터가 실림")
d.state("받는 쪽", "SYN cookie: no state until ACK", 292, INFO)
d.t(988, 312, "§3 자원을 늦게 잡아 플러드를 막습니다", 11, SOFT, KR, "end")

# ── 조이기 §1
d.msg("보내는 쪽", "받는 쪽", "데이터 세그먼트", 366, MUTED, sub="§1 보낼 수 있는 양은 두 창이 정함")
d.msg("받는 쪽", "보내는 쪽", "ACK + Window = rwnd", 408, INFO,
      sub="§1 수신 버퍼의 남은 자리를 숫자로 알려 줌")
d.state("받는 쪽", "app slow -> rwnd = 0", 444, WARN)
d.t(988, 464, "§1 영 창 교착 — 확인용 패킷으로 풀림", 11, SOFT, KR, "end")

# ── 혼잡 §4·§5
d.selfmsg("보내는 쪽", "손실·지연으로 cwnd 를 추정", 516,
          sub="§4 망은 알려 주지 않음 — 대가는 재전송과 지연")
d.state("보내는 쪽", "limit = min(cwnd, rwnd)", 566, OK)
d.t(24, 590, "§5 실제 한도는 둘 중 작은 쪽 — 병목 링크가 목표를 정합니다", 11, SOFT, KR, "start")

# ── 허물기 §2
d.msg("보내는 쪽", "받는 쪽", "FIN · ACK 네 번의 왕복", 624, MUTED, dash="5 4",
      sub="§2 먼저 닫는 쪽이 TIME_WAIT 를 떠안음")

d.t(12, 684, "소켓이 없으면 이 흐름 대신 RST 가 돌아옵니다 — §2 닫힌 포트와 조용한 폐기의 구분",
     11, MUTED, KR, "start")

d.legend(H - 40, [("연결 수립·해제", ACC), ("데이터·통보", INFO), ("송신 측 판단", OK)])
