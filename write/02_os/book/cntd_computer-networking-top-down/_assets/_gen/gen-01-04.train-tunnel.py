# 01-04 §1 — 전송 지연과 전파 지연이 서로 무관한 두 축이라는 것.
# 학습자가 "패킷을 만드는 시간이냐"를 두 번, "머리에서 잘 안 그려진다"를 한 번 되물은 자리다.
# 본문 근거: d(trans) 는 "패킷의 모든 비트를 링크로 밀어 넣음"이고 L/R 이며 거리와 무관,
#   d(prop) 는 "비트가 링크 반대편까지 건너감"이고 d/s 이며 패킷 길이·전송률과 무관.
#   전파 속도 범위도 본문이 준다 — 초속 2×10⁸ ~ 3×10⁸ 미터.
# 수치: 1,000바이트(8,000비트) ÷ 1 Gbps = 8 마이크로초 = 0.008 ms.
#   3,000 km ÷ 2×10⁸ m/s = 15 ms. 두 값 다 이 도식에서 직접 나눠 얻은 것이다.
# 타입 스펙: type-sequence — 네 사건이 시간순으로 쌓이고, 두 축이 서로 다른 구간을 차지하는 것이
#   세로 위치 그 자체로 드러난다. 축약: 세로 간격은 순서일 뿐 시간에 비례하지 않는다
#   (0.008 ms 와 15 ms 는 1,875배 차이라 선형 축에서는 앞쪽이 보이지 않는다). 그 사실을 아래 띠에 적었다.
import sys; sys.path.insert(0, ".")
from dd import Seq, ACC, MUTED, SOFT, INK, OK, INFO, PAPER2, RULE, KR, MONO

W, H = 1000, 720
d = Seq(W, H, "COMPUTER NETWORKING TOP-DOWN · 01-04 §1",
        "밀어 넣는 일과 건너가는 일은 따로입니다",
        "8,000량짜리 기차가 터널을 지나는 그림. 밀어 넣는 일은 송신 쪽에서만 일어나고 건너가는 일만 반대편에 닿는다. "
        "첫 량이 반대편으로 나올 때까지가 전파 지연이다. 하나를 줄여도 다른 하나는 그대로다.",
        "입구를 넓히는 일과 터널을 짧게 하는 일은 다른 공사입니다")

d.lanes([("송신 라우터", "터널 입구"), ("수신 라우터", "터널 출구")], y0=104, lane_w=260)
d.rails(470)

d.t(24, 232, "① 밀어 넣기", 12, ACC, KR, "start", 600)
d.t(24, 252, "L/R", 11, SOFT, MONO, "start")
d.selfmsg("송신 라우터", "첫 비트가 링크로", 262, ACC, sub="t = 0 — 첫 량이 터널로 들어갑니다")
d.selfmsg("송신 라우터", "마지막 비트가 링크로", 318, ACC, sub="t = 0.008 ms — 8,000번째 량이 들어갑니다")

d.line(24, 348, W - 24, 348, RULE, 0.8, "4 6")

d.t(24, 380, "② 건너가기", 12, INFO, KR, "start", 600)
d.t(24, 400, "d/s", 11, SOFT, MONO, "start")
d.msg("송신 라우터", "수신 라우터", "첫 비트 도착", 400, INFO, sub="t = 15 ms — 3,000 km 를 건너는 데 걸린 시간")
d.msg("송신 라우터", "수신 라우터", "마지막 비트 도착", 452, INFO, sub="t = 15.008 ms — 둘의 합")

d.box(24, 500, W - 48, 92, PAPER2, RULE, 0.9, 6)
d.t(44, 526, "만드는 시간이 아닙니다", 12, INK, KR, "start", 600)
d.t(44, 548, "패킷은 이미 만들어져 있습니다. 전송 지연은 그 8,000비트를 링크에 한 줄로 밀어 넣는 데 걸리는 시간이고 `8,000 ÷ 10⁹ = 0.008 ms` 입니다.",
    11, MUTED, KR, "start")
d.t(44, 570, "위아래 간격은 순서일 뿐 시간에 비례하지 않습니다. 두 값이 1,875배 차이라 같은 자로 그리면 ① 이 선 하나로 뭉갭니다.",
    11, SOFT, KR, "start")

d.tone(24, 604, 470, 56, ACC, 6, "10", 1.2)
d.t(44, 628, "입구를 넓히면 (R↑)", 11, ACC, KR, "start", 600)
d.t(44, 648, "① 만 짧아집니다. 터널 길이는 그대로입니다.", 11, MUTED, KR, "start")
d.tone(506, 604, 470, 56, INFO, 6, "10", 1.2)
d.t(526, 628, "터널을 짧게 하면 (d↓)", 11, INFO, KR, "start", 600)
d.t(526, 648, "② 만 짧아집니다. 입구 넓이는 그대로입니다.", 11, MUTED, KR, "start")

d.legend(H - 44, [("밀어 넣는 구간 — 전송 지연", ACC), ("건너가는 구간 — 전파 지연", INFO)])
d.save("01-04.train-tunnel.svg")
print("ok train-tunnel")
