# 20-01 「입출력을 기다리는 동안 다른 일을 한다」 — 스레드 하나로는 입출력 대기 동안 CPU 가 놀지만 스레드 둘이면 한 스레드가 기다리는 사이 다른 스레드가 계산한다.
# 본문 근거: 이 노트 「2. 스레드를 쓰는 이유」.
# 값 근거: 개념 도식이라 값은 없다. 구간 길이는 순서를 보이려는 것이지 시간이 아니다.
# 공식 근거: OSTEP 26장 §26.1 — 한 스레드가 입출력을 기다리는 동안(blocked) 스케줄러가 준비된 다른 스레드로 바꿔 입출력과 다른 활동을 겹친다.
# 타입 스펙: type-gantt — 시간축을 가로로 둔 구간 막대. 개념 도식이라 눈금은 없고 같은 가로축 위 두 시나리오(스레드 하나·둘)의 막대 순서만 맞댄다.
import sys; sys.path.insert(0, ".")
from dd import D, INK, MUTED, SOFT, RULE, PAPER2, ACC, OK, WARN, INFO, KR, MONO

W, H = 920, 460
d = D(W, H, "GANTT · 20-01 §2",
      "스레드가 둘이면 한 스레드의 입출력 대기 동안 다른 스레드가 계산한다",
      "스레드 하나짜리 프로그램은 계산, 입출력 대기, 계산 순으로 이어져 대기 구간 동안 CPU 를 쓰지 못한다. "
      "스레드 둘이면 스레드 1 이 입출력을 기다리는 동안 스레드 2 가 계산하고, 스레드 2 가 기다리는 동안 스레드 1 이 이어서 계산해 대기 구간이 계산으로 채워진다.",
      lead="가로가 시간 순서입니다. 막대 길이는 개념 표시이고 실제 시간이 아닙니다.")

X0 = 200
BH = 36


def bar(x, y, w, label, c, sub=None):
    d.tone(x, y, w, BH, c, 4, "22", 1.1)
    d.t(x + w / 2, y + 23, label, 13, c, KR, "middle", 600)


def rowlabel(y, t):
    d.t(X0 - 16, y + 23, t, 13, INK, KR, "end", 600)


d.t(X0, 108, "스레드 하나", 14, INK, KR, "start", 600)
rowlabel(124, "스레드 1")
bar(X0, 124, 160, "계산", INFO)
bar(X0 + 164, 124, 240, "입출력 대기", WARN)
bar(X0 + 408, 124, 160, "계산", INFO)
d.t(X0 + 288, 188, "이 구간에 CPU 가 놀고 있음", 13, WARN, KR, "middle", 600)

d.line(12, 216, W - 48, 216, RULE, 0.8)

d.t(X0, 252, "스레드 둘", 14, INK, KR, "start", 600)
rowlabel(268, "스레드 1")
bar(X0, 268, 160, "계산", INFO)
bar(X0 + 164, 268, 240, "입출력 대기", WARN)
bar(X0 + 408, 268, 160, "계산", INFO)
rowlabel(312, "스레드 2")
bar(X0 + 164, 312, 160, "계산", OK)
bar(X0 + 328, 312, 160, "입출력 대기", WARN)
d.t(X0 + 244, 372, "1 의 대기 구간을 2 의 계산이 채움", 13, OK, KR, "middle", 600)

d.legend(H - 40, [("계산", INFO), ("다른 스레드의 계산", OK), ("입출력 대기", WARN)])
d.save("20-01.io-overlap.svg")
print("ok 20-01 io-overlap")
