# 13-01 §2 클러스터 워크로드와 VM 이 신원을 얻는 두 경로 — 원문 그림 13.2 · 13.3.
# 본문(원문 13.1.1): Istio 는 쿠버네티스를 신뢰의 원천으로 삼아 VM 의 신원을 마련한다. 쿠버네티스에서
#       토큰을 만들어 기계로 옮기고, 기계의 istio-agent 가 그 토큰으로 istiod 에 인증하면 istiod 가
#       SPIFFE Verifiable Identity Document(SVID) 형태로 신원을 발급한다. 클러스터 워크로드는 파드에
#       주입된 서비스 어카운트 토큰을 그대로 써서 인증하고 SVID 를 받는다. VM 은 외부에 있으므로
#       (1) 서비스 어카운트 생성 (2) 토큰을 VM 으로 전송 (3) 그 토큰으로 인증 세 단계를 손으로 밟는다.
#       저자가 "유일한 차이는 쿠버네티스가 토큰을 파드에 자동 주입한다는 것" 이라고 적는다.
# 타입 스펙: type-sequence — 시간 순서가 논점이다. 참여자 4(최대 5), 메시지 9(최대 12), coral 은 한 곳.
#           축약: 파드와 VM 을 각각 레인으로 두면 레인이 다섯이 되어 화살표가 서로를 넘는다. 둘 다
#           "워크로드" 한 레인에 두고 상단·하단에서 state 칩으로 그때 무엇인지 밝힌다.
