# 고를 것인가'만 본다. 축을 갈라 둘이 같은 표가 되지 않게 한다.
import sys; sys.path.insert(0, ".")
from dd import D, ACC, INFO, OK, MUTED, SOFT, KR
import ddx

d = D(1240, 604, "KUBERNETES IN ACTION · 08-02",
      "값 몇 개인가, 설정 파일인가",
      "환경변수는 프로세스 환경에, 파일 마운트는 컨테이너 파일시스템에 놓인다. 담을 데이터의 모양이 "
      "둘 중 어느 쪽이 자연스러운지를 대개 정해 준다.",
      "같은 ConfigMap 을 어느 경로로 줄 것인가")

ddx.matrix(
    d, x0=24, hdr_y=148, row_h=88, gap=12, focal_col=1,
    cols=[(260, "묻는 것"), (330, "환경변수"), (330, "파일 마운트"), (250, "고르는 기준")],
    rows=[
        ([("앱이 읽는 대상", "어디서 값을 가져오나"), ("프로세스 환경", "System.getenv()"),
          ("컨테이너 파일시스템", "평소처럼 파일을 읽는다"),
          ("앱이 이미 하는 쪽", "")], INFO),
        ([("데이터의 모양", "무엇을 담나"), ("포트 · URL · 로그 레벨", "단순 값 몇 개"),
          ("계층 · 목록 · 멀티라인", "설정 파일 통째로"),
          ("구조가 있으면 파일", "")], ACC),
        ([("기존 형식", "그대로 쓸 수 있나"), ("이름으로 변환해야 한다", "SPRING_DATASOURCE_URL"),
          ("형식을 그대로 유지", "application.yml 그대로"),
          ("옮기는 비용", "")], OK),
    ])

d.t(24, 480, "값이 몇 개뿐이고 앱이 환경변수 바인딩을 지원하면 환경변수가 단순하다. "
             "기존 application.yml 을 유지해야 하거나 구조화된 설정이 크면 파일 마운트가 자연스럽다.",
     11, MUTED, KR, "start")
d.t(24, 502, "다만 파일이 갱신되더라도 앱이 시작할 때만 읽는다면, 동작을 바꾸려면 결국 Pod 를 교체해야 한다.",
     11, MUTED, KR, "start")
d.legend(528, [("경로", INFO), ("선택을 가르는 축", ACC), ("옮기는 비용", OK)])
d.save("08-02-env-vs-file-choice.svg")
