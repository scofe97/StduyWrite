# 12-02 §2 — 서로가 서로를 기다린다
# 순환 의존이 주제라 사슬이 아니라 고리로 그려야 한다. 고리 옆에 푸는 수를 따로 두어
# '순서를 앞으로 당겼다'가 보이게 한다.
import sys; sys.path.insert(0, ".")
from dd import D, ACC, INFO, OK, BAD, MUTED, SOFT, INK, KR, MONO
import ddx

d = D(1180, 632, "KUBERNETES IN ACTION · 12-02",
      "인증서를 고르려면 목적지를, 목적지를 읽으려면 인증서를",
      "한 IP 에 도메인이 여럿 얹히면서 생긴 문제다. 접속만 보고는 어느 인증서를 내밀지 알 수 없는데, "
      "그 답이 적힌 Host 헤더는 암호화된 본문 안에 있다.",
      "203.0.113.10 에 api · admin · shop 이 함께 얹혀 있다")

ddx.band(d, 100, 452, "닫힌 고리", x=24, w=680)
CY = [("인증서를 고른다", "목적지를 알아야 한다", 364, 190),
      ("암호를 푼다", "인증서가 있어야 한다", 570, 320),
      ("목적지를 읽는다", "Host 는 본문 안에 있다", 190, 320)]
for t, s, cx, cy in CY:
    ddx.node(d, cx, cy, t, s, 230, 84, BAD)
# 화살표는 '기다린다'. 박스 경계에서 출발·도착해야 하고, 안에서 시작하면 고리가 안 읽힌다.
# A 인증서(249~479 x 148~232) · B 암호(455~685 x 278~362) · C 목적지(75~305 x 278~362)
d.path("M 300 236 L 248 272", BAD, 1.5, m="bad")   # A → C
d.path("M 311 320 L 449 320", BAD, 1.5, m="bad")   # C → B
d.path("M 508 274 L 442 236", BAD, 1.5, m="bad")   # B → A
d.t(364, 268, "화살표는 '기다린다'", 10, SOFT, KR)
d.t(364, 414, "셋이 서로를 기다려 아무것도 시작되지 않는다", 11, BAD, KR)

ddx.band(d, 100, 452, "푸는 수 — 묻는 순서를 앞으로 당긴다", x=724, w=432)
d.t(940, 190, "핸드셰이크 맨 앞, 아직 아무것도", 11, MUTED, KR)
d.t(940, 210, "암호화되지 않은 자리에", 11, MUTED, KR)
ddx.node(d, 940, 282, "SNI", "server_name: api.example.com", 380, 88, focal=True)
d.t(940, 350, "클라이언트가 먼저 목적지를 밝히니", 11, ACC, KR)
d.t(940, 370, "서버가 인증서를 고를 수 있다", 11, ACC, KR)
d.t(940, 410, "봉투 겉면의 수취인 이름 같은 것", 11, SOFT, KR)

d.t(24, 496, "다만 겉면에 적힌 것은 수취인뿐이라 무엇을 요청하는지는 여전히 모른다 — "
             "passthrough 에서 호스트 분기만 되고 경로 분기가 안 되는 이유다.", 11, MUTED, KR, "start")
d.t(24, 518, "SNI 는 TLS(전송 계층)의 필드라 암호화 전에 오가고, Host 는 HTTP(응용 계층)의 헤더라 암호화 후에 실린다. "
             "같은 이름이 두 층에 한 번씩 적히는 셈이다.", 11, MUTED, KR, "start")
d.legend(552, [("닫힌 고리", BAD), ("고리를 푸는 자리", ACC)])
d.save("12-02-sni-chicken-and-egg.svg")
print("ok")
