# 05-01 §3 — Pod 는 무엇을 공유하고 무엇을 격리하는가
# 본문: "Network·UTS·IPC 세 가지는 기본으로 공유됩니다." / "PID 네임스페이스는 기본으로
#        공유되지 않습니다 ... shareProcessNamespace: true 를 명시적으로 켜야 합니다."
#       "각 컨테이너는 항상 자기만의 Mount 네임스페이스를 가져 ... 볼륨이라는 명시적 통로를
#        걸어야만 그 지점이 공유됩니다."
# 타입 스펙: type-dp-security-matrix.md — 축이 다섯이고 각 축마다 기본값·가능·불가능이 갈리므로 비교 행렬.
#           옛 판은 Pod 상자에 eth0·lo 를 그려 Network 하나만 보였다 — 부제는 UTS·IPC 를
#           말하는데 그림에는 없었고, PID 는 아예 빠져 있었다.
#           행은 네임스페이스 다섯, 열은 기본값·할 수 있는 것·못 하는 것인 격자다.
#           focal 열이 기본값이라 그 한 칸이 나머지 두 열을 정한다.
import sys; sys.path.insert(0, ".")
from dd import D, INK, MUTED, SOFT, RULE, ACC, OK, WARN, BAD, INFO, PAPER, PAPER2, KR, MONO
import ddx

W, H = 1000, 768
d = D(W, H, "KUBERNETES IN ACTION · 05-01",
      "Pod 는 일부만 공유한다 — 무엇이 공유되고 무엇이 격리되는가",
      "Network·UTS·IPC 는 기본으로 공유되고 PID 는 켜야 공유되며 Mount 는 항상 격리다. "
      "공유되는 것이 사이드카 패턴을 가능하게 하고, 격리되는 것이 그 대가를 만든다.",
      lead="Network 를 공유하니 localhost 로 부를 수 있고, 같은 포트에는 못 붙는다")

ddx.band(d, 104, 712, "공유는 능력과 제약을 함께 준다 — 한 칸에서 둘 다 읽힌다")

ddx.matrix(
    d, x0=32, hdr_y=196, row_h=76, gap=10, focal_col=1,
    cols=[(185, "네임스페이스"), (160, "기본값"),
          (275, "그래서 할 수 있는 것"), (270, "그래서 못 하는 것")],
    rows=[
        ([("Network", "인터페이스·IP·포트 공간"), ("공유", "끌 수 없다"),
          ("localhost:<포트> 로 부른다", "IP 를 몰라도 된다"),
          ("같은 포트에 못 붙는다", "A 가 8080 이면 B 는 못 쓴다")], OK),
        ([("UTS", "시스템 호스트명"), ("공유", "끌 수 없다"),
          ("같은 호스트명을 본다", "한 대처럼 보인다"),
          ("호스트명을 따로 못 준다", "컨테이너별로 지정할 수 없다")], OK),
        # 본문은 IPC 공유의 대가를 적지 않는다. '이름 충돌' 같은 말을 지어 넣지 않고,
        # PID 만 스위치를 가진다는 본문의 대비에서 나오는 사실까지만 적는다.
        ([("IPC", "프로세스 간 통신"), ("공유", "끌 수 없다"),
          ("보통의 IPC 로 통신한다", "기본값이라 설정이 없다"),
          ("IPC 로 서로를 격리 못 한다", "PID 와 달리 끄는 스위치가 없다")], OK),
        ([("PID", "프로세스 트리"), ("격리", "켤 수 있다"),
          ("shareProcessNamespace 로 켠다", "켜면 트리를 공유한다"),
          ("ps 에 서로 안 보인다", "시그널도 못 보낸다")], WARN),
        ([("Mount", "파일시스템"), ("항상 격리", "끌 수 없다"),
          ("볼륨을 양쪽에 마운트한다", "그 지점만 공유된다"),
          ("파일이 자동 공유되지 않는다", "통로를 명시해야 한다")], INFO),
    ])

d.t(36, 668, "같은 Pod 안 파일 공유는 emptyDir 이고 Pod 를 넘는 공유는 PersistentVolume 이다 — "
             "볼륨 종류가 공유의 경계를 가른다.", 12, MUTED, KR, "start")
d.t(36, 688, "다른 Pod 의 프로세스는 자기 인터페이스와 포트 공간을 가지므로 Pod 사이에는 포트 충돌이 없다.",
     12, MUTED, KR, "start")
d.legend(728, [("기본으로 공유", OK), ("기본은 격리 — 켤 수 있다", WARN),
               ("항상 격리 — 볼륨으로 뚫는다", INFO)])
d.save("05-01-pod-namespace-sharing.svg")
print("ok pod-namespace-sharing")
