# 11-02 §3 — 한 패킷에서 바뀌는 자리는 둘
# 필드 둘 × 정책 둘의 교차라 행렬. Local 열이 판정 축이므로 그 열을 focal 로 둔다.
# 타입 스펙: type-dp-security-matrix.md — 행은 바뀌는 자리 둘(DNAT·SNAT), 열은 두 정책의 판정. 목적지 행은 변환은 같고 대상 노드가
#           갈리며, 출발지 행은 변환 여부 자체가 갈린다.
import sys; sys.path.insert(0, ".")
from dd import D, ACC, INFO, MUTED, SOFT, KR
import ddx

d = D(988, 470, "KUBERNETES IN ACTION · 11-02",
      "한 패킷에서 바뀌는 자리는 둘",
      "노드 A 로 들어온 연결이 파드로 넘어갈 때 주소가 두 군데 바뀐다. 목적지는 두 정책 모두 파드 주소로 바꾸지만 "
      "Cluster 는 어느 노드 파드로든 넘기고 Local 은 노드 A 의 파드로만 넘긴다. 출발지는 Cluster 만 바꾼다. "
      "출발지를 바꾸느냐가 소스 IP 가 지워지느냐 남느냐를 정한다.",
      "PC 203.0.113.7 → 노드 A 172.18.0.4:30080 → 파드")

ddx.matrix(
    d, x0=24, hdr_y=148, row_h=92, gap=12, focal_col=3,
    cols=[(160, "바뀌는 자리"), (372, "무엇에서 무엇으로"), (176, "Cluster"), (196, "Local")],
    rows=[
        ([("목적지", "DNAT"), ("172.18.0.4:30080 → 파드 IP:8080", "안 바꾸면 파드에 닿지 못한다"),
          ("어느 노드 파드든",), ("노드 A 파드로만",)], INFO),
        ([("출발지", "SNAT"), ("203.0.113.7 → 172.18.0.4", "응답이 노드 A 로 돌아와야 한다"),
          ("바꾼다",), ("바꾸지 않는다",)], ACC),
    ])

d.t(24, 404, "Local 이 소스 IP 를 지키는 것은 지키는 장치가 있어서가 아니다. 자기 노드 위 파드로만 넘기니 "
             "응답이 딴 데로 샐 일이 없고, 그래서 출발지를 위조할 이유 자체가 없다.", 11, MUTED, KR, "start")
d.legend(430, [("변환은 같고 대상이 갈리는 자리", INFO), ("변환 여부가 갈리는 자리", ACC)])
d.save("11-02-dnat-snat-two-fields.svg")
print("ok")
