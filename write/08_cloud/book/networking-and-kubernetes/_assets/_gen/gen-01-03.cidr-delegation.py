# 01-03.cidr-delegation — CIDR 위임 계보, 단계마다 범위가 좁아진다
# 본문 요구(01-03 §2): "/N 은 네트워크부 비트 수라 N 이 클수록 좁다". 위임은 IANA → ARIN →
#           ISP → 기관 → 호스트로 내려가고, 몇 단계를 거치든 "최종 호스트는 처음 블록 밖으로
#           나가지 않는다". 그래서 계단은 갈라지지 않고 한 줄로만 내려간다 — 본문이 "윗줄은
#           그중 하나만 따라간 것"이라고 밝혀 둔 그 한 줄이다.
# 타입 스펙: type-bar.md — 범주(위임 단계)별 수치(담는 주소 수)를 막대 길이로 비교한다.
#           2,097,152 대 1 은 선형으로 못 그려 로그 눈금을 쓴다. 막대 길이는 log2(개수+1)에
#           비례하고 실제 수치는 막대 오른쪽에 글자로 적었다 — 축 라벨에도 "로그 눈금"을 밝힌다.
#           왼쪽 계단 들여쓰기와 화살표는 포함 관계를 나르는 보조 축이다.
#           스펙의 "focal 막대 하나" 규약과는 어긋나 색이 셋이다 — 넓은 위임(파랑)·좁아지는
#           중(노랑)·단일 호스트(주황)라는 구간 구분이고 범례가 그 셋을 받는다.
# 이력: 2026-08-28 신설. 생성기 없이 손으로 만들어진 SVG 였다. 값·문구는 그대로 옮겼고,
#           위임선 넷이 3px 씩 기울어 dd-lint diagonal 4건에 걸리던 것만 세로로 폈다.
#           그 자리를 만들려고 행 간격을 76→84 로, 높이를 558→590 으로 늘렸다.
import math
from dd import D, INK, MUTED, SOFT, RULE, ACC, WARN, INFO, KR, MONO

W, H = 1000, 590
X0, Y0, ROW_H, STRIDE = 12, 124, 68, 84
INDENT, NARROW = 26, 8          # 단계마다 왼쪽으로 들여쓰고 그만큼 폭이 준다
TX, TW, TH = 430, 426, 24       # 막대 트랙
MAXBITS = 21                    # /11 의 호스트부 비트 수 — 로그 눈금의 만점

ROWS = [("IANA",   "208.128.0.0/11",   2097152, INFO),
        ("ARIN",   "208.130.0.0/16",     65536, INFO),
        ("ISP",    "208.130.28.0/22",     1024, WARN),
        ("기관",   "208.130.29.0/24",      256, WARN),
        ("호스트", "208.130.29.33/32",       1, ACC)]

d = D(W, H, "DELEGATION TREE · 01-03 CIDR",
      "CIDR 위임 계보 — 단계마다 범위가 좁아진다",
      "208.130.29.33의 위임 계보. IANA가 /11을 ARIN에 주고, ARIN이 점점 작은 서브넷으로 쪼개 "
      "내려가 최종적으로 단일 호스트 /32에 닿는다. 프리픽스 숫자가 커질수록 담는 주소 수가 줄어든다.",
      lead="프리픽스가 길어질수록 담는 주소가 줄어듭니다 — 막대는 로그 눈금입니다.")

for i, (who, cidr, count, c) in enumerate(ROWS):
    x, y, w = X0 + INDENT * i, Y0 + STRIDE * i, 300 - NARROW * i
    if i:                       # 위임선은 다음 칸을 그리기 전에 — 칸이 불투명이라 나중에 그리면 덮인다.
        # 부모 안쪽에서 곧장 아래로 떨어져 자식의 윗변으로 들어간다. 비스듬한 선은
        # house 계약이 금한다(dd-lint diagonal) — 들여쓰기가 이미 포함 관계를 나르므로
        # 선까지 기울일 이유가 없다. 그 대신 칸 사이를 16px 로 벌려 선이 보이게 했다.
        d.path(f"M {x+30} {y-STRIDE+ROW_H} L {x+30} {y}", MUTED, 1.4, m="ar")
    d.tone(x, y, w, ROW_H, c, 6, "12", 1.2)
    d.t(x + 16, y + 26, who, 12, c, KR, "start", 600)
    d.t(x + 16, y + 46, cidr, 12, INK, MONO, "start")
    ty = y + 22
    d.box(TX, ty, TW, TH, "#161B22", RULE, 0.8, 4)
    d.tone(TX, ty, TW * math.log2(count + 1) / MAXBITS, TH, c, 4, "44", 1.1)
    d.t(TX + TW + 10, ty + 17, f"{count:,}", 11, c, MONO, "start", 600)

d.t(TX, 114, "담는 주소 수 (로그 눈금)", 11, SOFT, MONO, "start")
d.legend(546, [("넓은 위임", INFO), ("좁아지는 중", WARN), ("단일 호스트", ACC)])
d.save("01-03.cidr-delegation.svg")
print("ok cidr-delegation")
