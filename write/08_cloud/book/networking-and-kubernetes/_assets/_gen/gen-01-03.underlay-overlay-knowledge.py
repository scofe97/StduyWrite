# 01-03.underlay-overlay-knowledge — 어느 네트워크가 어느 주소를 아는가
# 본문 요구(01-03 §7): 주소가 두 벌이고 "두 벌을 정한 주체가 다르고, 그 차이가 무엇을 아는지를
#           정한다". 그리고 본문이 곧바로 못 박는다 — "하부가 그 주소를 모르는 것은 능력의
#           문제가 아니다. VPC 라우터도 표를 갖고 있고 항목을 더 넣을 능력도 있다. 다만 그 표가
#           우리 것이 아니다." 그래서 판단 축은 클라우드냐 온프레미스냐가 아니라 "하부에 Pod
#           블록을 알려 줄 수단이 있는가"이고, 그 한 칸이 VXLAN 이냐 BGP 냐를 가른다.
#           네 번째 열이 그 축이라 focal 로 칠했다.
# 타입 스펙: type-dp-security-matrix.md — 행은 두 층(오버레이·하부), 열은 그 층을 묻는 네 가지
#           (층·주소 예·누가 정했나·라우팅 표를 만질 수 있나). 마지막 열이 판정 축이다.
#           아래 두 칸은 그 판정이 갈리는 두 경우와 각각의 결말을 나란히 둔 것이다.
# 이력: 2026-08-28 신설. 이 한 장만 dd 프리미티브가 아니라 손으로 쓴 SVG 였다 — 여백 100,
#           defs 없음, tspan 강조로 이 폴더 어느 도식과도 형태가 달랐다. 원문 문구·수치·판정을
#           그대로 두고 배치만 house 스타일(여백 12, 행렬 프리미티브, 범례)로 다시 세웠다.
#           문자열을 그대로 뱉는 생성기를 쓰면 dd-lint 가 검사할 것이 없어져 선언의 뜻이 없다.
import ddx
from dd import D, INK, MUTED, SOFT, RULE, ACC, OK, WARN, INFO, PAPER2, KR, MONO

W, H = 1000, 570
X0, GAP = 12, 24
PW = (W - X0 * 2 - GAP) / 2     # 아래 두 칸이 좌우를 반씩 쓴다

d = D(W, H, "WHO KNOWS WHAT · 01-03 OVERLAY",
      "어느 네트워크가 어느 주소를 아는가",
      "노드 주소와 Pod 주소를 두 층으로 나눠, 각 층을 누가 통제하고 어느 주소를 아는지 대조한 표. "
      "위층은 쿠버네티스가 정한 Pod 주소가 사는 오버레이이고, 아래층은 클라우드나 회사가 통제하는 "
      "하부 네트워크다. 하부가 Pod 주소를 모른다는 칸을 초점으로 강조했다.",
      lead="주소가 두 벌 있습니다. 각 벌을 누가 정했는지가 무엇을 아는지를 정합니다.")

ddx.matrix(d, X0,
           [(236, "층"), (200, "주소 예"), (236, "누가 정했나"), (244, "라우팅 표를 만질 수 있나")],
           [([("오버레이", "Pod 네트워크"), ("10.244.1.5", "10.244.2.7"),
              ("쿠버네티스", "우리가 값을 고른다"), ("예 — 우리 것이다",)], OK),
            ([("하부 네트워크", "노드가 올라앉은 망"), ("192.168.0.10", "192.168.0.20"),
              ("클라우드 · 회사", "빌려 쓰거나 소유한다"), ("경우에 따라 다르다",)], WARN)],
           hdr_y=118, row_h=84, gap=12, focal_col=3)

d.t(X0, 342, "하부가 Pod 주소를 아는가 — 이 한 칸이 방식을 가른다", 11, SOFT, KR, "start")

PANELS = [
    (X0, ACC, True,
     "모른다 — 알려 줄 수단이 없다",
     ["클라우드 VPC 라우터는 우리 것이 아니라", "표에 Pod 블록을 넣어 줄 수 없습니다."],
     "→ VXLAN 으로 노드 주소에 싸서 보낸다"),
    (X0 + PW + GAP, OK, False,
     "안다 — 알려 줄 수단이 있다",
     ["온프레미스 라우터는 관리자가 만지고,", "노드 광고를 받게 설정할 수 있습니다."],
     "→ BGP 로 블록을 광고해 직접 전달"),
]

for x, c, focal, head, body, verdict in PANELS:
    if focal:
        d.tone(x, 356, PW, 112, c, 6, "12", 1.4)
    else:
        d.box(x, 356, PW, 112, PAPER2, RULE, 1.0)
    d.t(x + 20, 384, ddx.fit(head, 14, PW - 40, head), 14, c, KR, "start", 600)
    for i, line in enumerate(body):
        d.t(x + 20, 410 + i * 20, ddx.fit(line, 12, PW - 40, line), 12, MUTED, KR, "start")
    d.t(x + 20, 452, ddx.fit(verdict, 13, PW - 40, verdict), 13, INK, KR, "start", 600)

# 주어를 줄이면 "모른다는 것" 이 무엇을 모른다는 말인지 그림에서 다시 찾아야 한다.
d.t(X0, 500, "하부가 Pod 주소를 모르는 것은 능력의 문제가 아니라 통제권의 문제입니다 — "
             "수단이 열리면 오버레이가 필요 없습니다.", 11, ACC, KR, "start")
d.legend(524, [("우리가 값을 정한다", OK), ("남의 표라 장담 못 한다", WARN),
               ("알려 줄 수단이 없는 쪽", ACC)])
d.save("01-03.underlay-overlay-knowledge.svg")
print("ok underlay-overlay-knowledge")
